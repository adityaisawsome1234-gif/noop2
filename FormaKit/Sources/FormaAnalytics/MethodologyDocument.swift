import Foundation
import FormaCore

/// The metric specifications as Markdown: what `forma-docs` prints into `docs/METHODOLOGY_SPECS.md`.
/// A test compares that file with this rendering, so the published specifications cannot drift from
/// the catalog compiled into the app.
public enum MethodologyDocument {
    static func statusText(_ s: MetricStatus) -> String {
        switch s {
        case .measured: return "Measured by the band"
        case .estimate: return "Forma estimate (documented method)"
        case .experimental: return "Experimental (Forma-defined)"
        }
    }

    public static func markdown(_ specs: [MetricSpec] = MetricCatalog.all) -> String {
        var out = "<!-- Generated by `swift run forma-docs` from FormaAnalytics.MetricCatalog. Do not edit by hand. -->\n\n"
        out += "# Metric specifications (generated)\n\n"
        out += "| Metric | ID | Version | Status | Unit |\n|---|---|---|---|---|\n"
        for s in specs {
            out += "| \(s.name) | `\(s.id)` | \(s.version) | \(statusText(s.status)) | \(s.unit) |\n"
        }
        for s in specs {
            out += "\n## \(s.name)\n\n"
            out += "- **ID / version:** `\(s.id)` v\(s.version)\n- **Status:** \(statusText(s.status))\n- **Unit:** \(s.unit)\n"
            out += "\n**Method.** \(s.method)\n\n**Window.** \(s.windowing)\n"
            if let b = s.baseline { out += "\n**Baseline.** \(b)\n" }
            out += "\n**Required inputs**\n" + s.requiredInputs.map { "- \($0)" }.joined(separator: "\n") + "\n"
            out += "\n**Quality gates**\n" + s.qualityGates.map { "- \($0)" }.joined(separator: "\n") + "\n"
            out += "\n**Limitations**\n" + s.limitations.map { "- \($0)" }.joined(separator: "\n") + "\n"
            if !s.references.isEmpty { out += "\n**References**\n" + s.references.map { "- \($0)" }.joined(separator: "\n") + "\n" }
        }
        return out
    }
}
